import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:nsl_dev/core/ddl/ddl_generator.dart';
import 'package:nsl_dev/core/l10n/l10n.dart';
import 'package:nsl_dev/core/models/enums.dart';
import 'package:nsl_dev/core/validate/validator.dart';
import 'package:nsl_dev/main.dart';
import 'package:nsl_dev/state/app_settings.dart';
import 'package:nsl_dev/state/project_controller.dart';
import 'package:nsl_dev/ui/home_page.dart';
import 'package:nsl_dev/ui/language_dialog.dart';
import 'package:nsl_dev/ui/shortcuts_help.dart';
import 'package:nsl_dev/ui/theme.dart';
import 'package:provider/provider.dart';

import 'migration_fixtures.dart';

final _thai = RegExp(r'[฀-๿]');

void main() {
  tearDown(() {
    currentLang = Lang.th;
    C.use(kLightPalette);
  });

  group('tr()', () {
    test('ภาษาไทย = คืนข้อความเดิมและแทนค่า {n}', () {
      currentLang = Lang.th;
      expect(tr('คัดลอก {0} ตาราง', [3]), 'คัดลอก 3 ตาราง');
    });

    test('ภาษาอังกฤษ = คืนคำแปล และข้อความที่ไม่มีคำแปลจะคืนต้นฉบับ', () {
      currentLang = Lang.en;
      expect(tr('คัดลอก {0} ตาราง', [3]), 'Copied 3 table(s)');
      expect(tr('ข้อความที่ไม่มีคำแปล'), 'ข้อความที่ไม่มีคำแปล');
    });

    test('ตัวบอกบริบท @@ : ไทยตัดทิ้ง, อังกฤษเลือกคำแปลตามบริบท', () {
      currentLang = Lang.th;
      expect(tr('ปิด@@disable'), 'ปิด');
      expect(tr('ปิด'), 'ปิด');
      currentLang = Lang.en;
      expect(tr('ปิด@@disable'), 'disable');
      expect(tr('ปิด'), 'Close');
    });
  });

  group('ผลลัพธ์ core เป็นอังกฤษเมื่อเลือกอังกฤษ', () {
    test('DDL header ไม่มีอักษรไทย', () {
      currentLang = Lang.en;
      final sql = DdlGenerator.forDialect(Dialect.mysql).generate(base());
      expect(sql, contains('generated by NSL Dev'));
      expect(_thai.hasMatch(sql), false, reason: sql);
    });

    test('ข้อความจากตัวตรวจ schema ไม่มีอักษรไทย', () {
      currentLang = Lang.en;
      final p = base();
      p.tables.first.columns.clear(); // ตารางไม่มีคอลัมน์ -> มีปัญหาให้รายงาน
      final issues = validateProject(p);
      expect(issues, isNotEmpty);
      for (final i in issues) {
        expect(_thai.hasMatch('${i.title} ${i.message}'), false, reason: '${i.title} / ${i.message}');
      }
    });
  });

  group('AppSettings', () {
    test('ไฟล์ไม่มี = ถือว่าเปิดครั้งแรก (ต้องถามภาษา)', () {
      final dir = Directory.systemTemp.createTempSync('nsl_settings');
      addTearDown(() => dir.deleteSync(recursive: true));
      final s = AppSettings.load(File('${dir.path}/settings.json'));
      expect(s.needsLanguagePrompt, true);
      expect(s.dark, false);
    });

    test('เลือกภาษา/ธีมแล้วบันทึก และครั้งหน้าไม่ถามอีก', () {
      final dir = Directory.systemTemp.createTempSync('nsl_settings');
      addTearDown(() => dir.deleteSync(recursive: true));
      final f = File('${dir.path}/settings.json');
      final s = AppSettings.load(f)
        ..setLang(Lang.en)
        ..setDark(true);
      expect(currentLang, Lang.en);
      expect(f.existsSync(), true);

      final again = AppSettings.load(f);
      expect(again.needsLanguagePrompt, false);
      expect(again.lang, Lang.en);
      expect(again.dark, true);
      expect(s.lang, Lang.en);
    });

    test('ไฟล์เสีย = ไม่พัง และถามภาษาใหม่', () {
      final dir = Directory.systemTemp.createTempSync('nsl_settings');
      addTearDown(() => dir.deleteSync(recursive: true));
      final f = File('${dir.path}/settings.json')..writeAsStringSync('{ not json');
      expect(AppSettings.load(f).needsLanguagePrompt, true);
    });
  });

  group('หน้าจอ', () {
    Future<void> setup(WidgetTester tester) async {
      tester.view.physicalSize = const Size(1440, 900);
      tester.view.devicePixelRatio = 1;
      addTearDown(tester.view.reset);
      tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(SystemChannels.platform, (call) async => null);
      addTearDown(() => tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(SystemChannels.platform, null));
    }

    testWidgets('เปิดครั้งแรกถามภาษา -> เลือก English แล้วหน้าจอเป็นอังกฤษและไม่ถามซ้ำ', (tester) async {
      await setup(tester);
      final dir = Directory.systemTemp.createTempSync('nsl_settings');
      addTearDown(() => dir.deleteSync(recursive: true));
      final f = File('${dir.path}/settings.json');
      await tester.pumpWidget(NslDevApp(settings: AppSettings.load(f)));
      await tester.pumpAndSettle();

      expect(find.byType(LanguageDialog), findsOneWidget);
      await tester.tap(find.text('English'));
      await tester.pumpAndSettle();

      expect(find.byType(LanguageDialog), findsNothing);
      expect(currentLang, Lang.en);
      expect(find.text('File'), findsOneWidget); // เมนูไฟล์
      expect(f.readAsStringSync(), contains('"lang":"en"'));
    });

    testWidgets('เลือกภาษาไทยก็ได้ และเมนูเป็นไทย', (tester) async {
      await setup(tester);
      final s = AppSettings(); // ยังไม่เลือก
      await tester.pumpWidget(NslDevApp(settings: s));
      await tester.pumpAndSettle();
      await tester.tap(find.text('ไทย'));
      await tester.pumpAndSettle();
      expect(find.text('ไฟล์'), findsOneWidget);
    });

    testWidgets('ข้อความบนหน้าหลัก (อังกฤษ) ไม่มีอักษรไทยหลุด รวมเมนูและหน้าคีย์ลัด', (tester) async {
      await setup(tester);
      await tester.pumpWidget(NslDevApp(settings: AppSettings(lang: Lang.en)));
      await tester.pumpAndSettle();
      final ctx = tester.element(find.byType(HomePage));
      final c = ctx.read<ProjectController>();
      c.loadProject(base(), null);
      await tester.pumpAndSettle();

      List<String> thaiTexts() => [
            for (final e in find.byType(Text).evaluate())
              if (_thai.hasMatch((e.widget as Text).data ?? (e.widget as Text).textSpan?.toPlainText() ?? ''))
                (e.widget as Text).data ?? (e.widget as Text).textSpan!.toPlainText(),
          ];

      expect(thaiTexts(), isEmpty, reason: 'หน้าหลัก');

      for (final menu in ['File', 'Edit', 'View', 'Help']) {
        await tester.tap(find.text(menu));
        await tester.pumpAndSettle();
        // ตัวเลือกภาษาในเมนูช่วยเหลือเป็นชื่อภาษาเอง (ไทย) จึงยกเว้น
        expect(thaiTexts().where((t) => t.trim() != 'ไทย'), isEmpty, reason: 'เมนู $menu');
        await tester.tapAt(const Offset(5, 880));
        await tester.pumpAndSettle();
      }

      showShortcutsHelp(ctx);
      await tester.pumpAndSettle();
      expect(find.byType(ShortcutsHelpDialog), findsOneWidget);
      expect(thaiTexts(), isEmpty, reason: 'หน้าคีย์ลัด');
    });

    testWidgets('สลับธีมมืด: พาเลตต์เปลี่ยน, สร้างหน้าใหม่ได้ไม่พัง และสลับกลับได้', (tester) async {
      await setup(tester);
      final s = AppSettings(lang: Lang.th);
      await tester.pumpWidget(NslDevApp(settings: s));
      await tester.pumpAndSettle();
      expect(C.isDark, false);

      await tester.tap(find.byIcon(Icons.dark_mode_outlined));
      await tester.pumpAndSettle();
      expect(s.dark, true);
      expect(C.isDark, true);
      expect(tester.takeException(), isNull);
      final scaffold = tester.widget<Scaffold>(find.byType(Scaffold).first);
      expect(scaffold.backgroundColor ?? Theme.of(tester.element(find.byType(Scaffold).first)).scaffoldBackgroundColor,
          kDarkPalette.bg);

      await tester.tap(find.byIcon(Icons.light_mode_outlined));
      await tester.pumpAndSettle();
      expect(C.isDark, false);
    });

    testWidgets('สลับธีมไม่ทำให้ถามกู้คืนซ้ำ และไม่เสียงานในโปรเจกต์', (tester) async {
      await setup(tester);
      final s = AppSettings(lang: Lang.th);
      await tester.pumpWidget(NslDevApp(settings: s));
      await tester.pumpAndSettle();
      final c = tester.element(find.byType(HomePage)).read<ProjectController>();
      c.loadProject(base(), null);
      await tester.pump();
      s.toggleDark();
      await tester.pumpAndSettle();
      expect(tester.element(find.byType(HomePage)).read<ProjectController>().project.tables.length, 2);
    });
  });

  test('ภาพ export ใช้พาเลตต์สว่างเสมอ แม้แอปอยู่ธีมมืด', () {
    C.use(kDarkPalette);
    final inside = C.withPalette(kLightPalette, () => C.canvas);
    expect(inside, kLightPalette.canvas);
    expect(C.canvas, kDarkPalette.canvas); // คืนค่าเดิมหลังจบ
  });
}
